#!/bin/bash
# Главный скрипт запуска run-dwh.sh

set -eu
# set -a; . .env; set +a

# if [ "$EUID" -ne 0 ]; then
#     sudo echo "Далее нужны будут права sudo..."
# fi

# Загрузка переменных окружения
. ./gitlabenv.sh

# echo "Запускаем кластер..."
# docker compose up -d


echo "Starting DWH Cluster Initialization..."
echo "   GitLab URL: ${GITLAB_URL}"
echo "   Registry: ${REGISTRY_URL}"

# ---------------------------------------------------------------------------- #
#                         1. Ждём готовности сервисов                          #
# ---------------------------------------------------------------------------- #
echo "Waiting for GitLab to be ready..."
until curl -sSf "${GITLAB_URL}/users/sign_in" >/dev/null 2>&1; do
    echo "   GitLab not ready, waiting 30s..."
    sleep 30
done
echo "GitLab is ready"

echo "Waiting for Registry to be ready..."
until curl -sSf "http://${REGISTRY_URL}/v2/" >/dev/null 2>&1; do
    echo "   Registry not ready, waiting 10s..."
    sleep 10
done
echo "Registry is ready"

# ---------------------------------------------------------------------------- #
#                            2. Выбор режима работы                            #
# ---------------------------------------------------------------------------- #

# режим safe
# - если проект не существует, он создается и заполняется
# - если проект есть и пустой, он заполняется
# - если проект есть и не пустой, то пропускается
# режим force
# - если проект есть, удаляется и создается заново, затем заливается код
# - если проекта нет, то обычное создание и заливка
MODE="${1:-safe}"   # safe (по умолчанию) или --force

if [[ "${MODE}" == "--force" ]]; then
  echo "Режим: FORCE (проекты будут пересоздаваться)"
else
  echo "Режим: SAFE (существующие непустые проекты будут пропущены)"
  MODE="safe"
fi

# ---------------------------------------------------------------------------- #
#                         3. Запускаем инициализацию GitLab                    #
# ---------------------------------------------------------------------------- #
echo ""
echo "=== Running gitlab-init.sh ==="
# /usr/local/bin/gitlab-init.sh
. ./gitlab-init.sh

# ---------------------------------------------------------------------------- #
#                         4. Загружаем Docker-образы в registry                #
# ---------------------------------------------------------------------------- #
echo ""
echo "=== Loading Docker images to registry ==="
# Здесь можно вызвать load-images.sh или встроить логику
. ./registry-init.sh

# ---------------------------------------------------------------------------- #
#                         5. Инициализируем репозитории GitLab                 #
# ---------------------------------------------------------------------------- #
echo ""
echo "=== Running repository-init.sh ==="
. ./repository-init.sh

# ---------------------------------------------------------------------------- #
#                         6. Инициализируем Airflow                            #
# ---------------------------------------------------------------------------- #
echo ""
echo "=== Running airflow-init.sh ==="
. ./airflow-init.sh

# ---------------------------------------------------------------------------- #
#                             7. Настройка Jenkins                             #
# ---------------------------------------------------------------------------- #
echo ""
echo "=== Running jenkins-init.sh ==="
# . ./jenkins-init.sh
. ./jenkins-init-debug.sh

echo ""
echo "All initialization complete!"
